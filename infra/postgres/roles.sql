\set ON_ERROR_STOP on
CREATE ROLE core LOGIN PASSWORD :'core_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
CREATE ROLE questions LOGIN PASSWORD :'questions_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
CREATE ROLE email LOGIN PASSWORD :'email_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
CREATE SCHEMA core AUTHORIZATION core;
CREATE SCHEMA questions AUTHORIZATION questions;
CREATE SCHEMA email AUTHORIZATION email;
REVOKE ALL ON SCHEMA core FROM PUBLIC;
REVOKE ALL ON SCHEMA questions FROM PUBLIC;
REVOKE ALL ON SCHEMA email FROM PUBLIC;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
ALTER ROLE core SET search_path = core;
ALTER ROLE questions SET search_path = questions;
ALTER ROLE email SET search_path = email;
